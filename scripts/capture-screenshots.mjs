// Runs the demo story against the running app and saves the deck screenshots to docs/screenshots.
// Usage: BASE=http://localhost:5173 node scripts/capture-screenshots.mjs   (then: cd presentation && npm run build)
import path from 'node:path';
const base = process.env.BASE ?? 'http://localhost:5173';
const out = 'docs/screenshots';
const browser = await chromium.launch();
const ctx = await browser.newContext({ viewport: { width: 430, height: 932 }, deviceScaleFactor: 2 });
const page = await ctx.newPage();
const shot = (name) => page.screenshot({ path: `${out}/${name}.png` });
await page.request.post(`${base}/api/demo/reset`);

await page.goto(`${base}/create?as=stu-jordan`);
await page.getByRole('button', { name: 'Demo example' }).click();
await page.getByTestId('cover-input').setInputFiles(path.resolve('docs/demo-assets/game-night-cover.jpg'));
await page.waitForTimeout(800);
await shot('01-create-event');
await page.getByRole('button', { name: 'Publish event' }).click();
await page.waitForTimeout(1200);
await shot('02-event-published');

await page.goto(`${base}/welcome?as=stu-maya`);
await page.waitForTimeout(800);
await shot('03-welcome');
await page.getByRole('button', { name: 'Find My Matches' }).click();
await page.getByRole('radio', { name: /Marietta Campus/ }).click();
await page.getByRole('button', { name: 'Continue' }).click();
for (const i of ['Gaming', 'Technology & Coding', 'Social Events']) await page.getByRole('button', { name: i }).click();
await page.waitForTimeout(400);
await shot('04-interests');
await page.getByRole('button', { name: 'Continue' }).click();
await page.getByRole('button', { name: 'Yes, definitely' }).click();
await page.getByRole('button', { name: 'Small groups' }).click();
await page.getByRole('button', { name: 'Relaxed' }).click();
await page.getByRole('button', { name: 'Continue' }).click();
await page.getByLabel('About you').fill("I'm a software engineering student into gaming and programming. I want to make friends, but I prefer casual, small-group hangouts.");
await shot('05-about-you');
await page.getByRole('button', { name: 'Continue' }).click();
await page.getByRole('button', { name: 'Weekends' }).click();
await page.getByRole('button', { name: 'Evenings' }).click();
await page.getByRole('button', { name: 'Build my matches' }).click();
await page.getByRole('heading', { name: /You're all set/ }).waitFor({ timeout: 30000 });
await page.waitForTimeout(500);
await shot('06-ai-profile');
await page.getByRole('button', { name: 'Start discovering' }).click();
await page.getByRole('article').first().waitFor();
await page.waitForTimeout(1500);
await shot('07-discover-recommendation');
await page.getByRole('button', { name: 'Interested', exact: true }).click();
await page.getByRole('dialog').waitFor();
await page.getByRole('dialog').getByText('Show me to others going').click();
await page.getByRole('dialog').getByText('Host').waitFor();
await page.waitForTimeout(600);
await shot('08-going-together');
await page.getByRole('dialog').getByRole('button', { name: 'Keep swiping' }).click();
await page.goto(`${base}/matches?as=stu-maya`);
await page.waitForTimeout(1000);
await shot('09-my-matches');
await page.goto(`${base}/ai?as=stu-maya`);
await page.getByRole('button', { name: /Find me something fun on Marietta/ }).click();
await page.getByText(/Searching campus activities/).waitFor({ state: 'detached', timeout: 40000 });
await page.waitForTimeout(800);
await shot('10-concierge');

const desk = await browser.newPage({ viewport: { width: 1440, height: 900 }, deviceScaleFactor: 1.5 });
await desk.goto(`${base}/ai?as=stu-maya`);
await desk.getByRole('tab', { name: 'Why AI?' }).click();
await desk.getByText('Category filter only').waitFor({ timeout: 60000 });
await desk.waitForTimeout(800);
await desk.screenshot({ path: `${out}/11-why-ai-desktop.png` });
await desk.goto(`${base}/discover?as=stu-sam`);
await desk.getByRole('article').first().waitFor({ timeout: 60000 });
await desk.waitForTimeout(800);
await desk.screenshot({ path: `${out}/12-discover-desktop.png` });
await browser.close();
console.log('done');
